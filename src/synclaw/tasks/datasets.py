"""Dataset conversion utilities for LLM-facing synthesis tasks."""

from __future__ import annotations

import hashlib
import json
import random
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from synclaw.core import chem
from synclaw.tools.contracts import (
    TASK_FLAG_FIELDS,
    TASK_OVERRIDE_FIELDS,
    TOOL_NAMES,
    UNLIMITED_BUDGET,
    normalize_excluded_tools,
    task_budget_overrides,
)

DEFAULT_PROMPT_TEMPLATE = "Target molecule: {target_smiles}"

DEFAULT_SYSTEM_PROMPT = """You are performing synthesis planning. Return a proposed synthesis pathway for the exact target when possible. If exact synthesis is not found, return the highest-similarity analogue you can identify. Submit pathways with submit_pathway, which you may call more than once; only your best accepted pathway counts. Each must either contain at least one reaction step that the validator can reproduce, or a single valid building_block for direct purchase."""

PROMPT_FINGERPRINT = hashlib.sha256(
    "\0".join((DEFAULT_PROMPT_TEMPLATE, DEFAULT_SYSTEM_PROMPT)).encode("utf-8")
).hexdigest()[:12]


def build_llm_task(
    target_smiles: str,
    *,
    task_id: str,
    dataset: str,
    source_file: str,
    excluded_tools: Sequence[str] = (),
    budgets: Mapping[str, int | bool] | None = None,
) -> dict[str, Any]:
    """Build one validated LLM-facing synthesis task.

    ``excluded_tools`` are hidden from the model for this task, on top of any the run excludes.
    ``budgets`` override the runner's budgets for this task; fields left out keep the runner's.
    """

    excluded = normalize_excluded_tools(excluded_tools)
    budget_overrides = _validated_budget_set(budgets or {})

    validation = chem.validate_smiles(target_smiles)
    if not validation["valid"]:
        raise ValueError(
            f"Invalid target SMILES for task {task_id!r}: "
            f"{validation.get('error') or target_smiles!r}"
        )
    canonical = validation["canonical_smiles"]
    identity = chem.compare_molecular_identity(canonical, canonical)
    if not identity["valid"]:
        raise ValueError(
            f"Target SMILES for task {task_id!r} can never be matched exactly "
            f"({identity['error']}): {target_smiles!r}"
        )
    return {
        "task_id": task_id,
        "dataset": dataset,
        "source_file": source_file,
        "target_smiles": target_smiles,
        "canonical_target_smiles": canonical,
        "question": DEFAULT_PROMPT_TEMPLATE.format(
            target_smiles=target_smiles,
            task_id=task_id,
            dataset=dataset,
        ),
        "system_prompt": DEFAULT_SYSTEM_PROMPT,
        "prompt_fingerprint": PROMPT_FINGERPRINT,
        "excluded_tools": sorted(excluded),
        "available_tools": [name for name in TOOL_NAMES if name not in excluded],
        **budget_overrides,
        "expected_final_tool": "submit_pathway",
        "expected_submission": {
            "steps": [
                {
                    "reaction_id": "reaction template ID",
                    "reactants": [
                        "BB:<id> or INT:<step_number> or raw reactant SMILES"
                    ],
                    "product_smiles": "SMILES generated by this reaction step",
                }
            ],
            "pathway_text": "natural language explanation of the route",
        },
        "scoring": {
            "primary": [
                "valid RDKit-generated final product",
                "similarity_to_target",
                "building_block_grounding",
                "complete tool-use trace",
            ]
        },
    }


def parse_budget_set(text: str) -> dict[str, int | bool | str]:
    """Parse ``max_turns=40,token_budget_feedback=false`` into task budget overrides; 'none' is empty."""

    if text.strip() == "none":
        return {}
    budgets: dict[str, Any] = {}
    for item in text.split(","):
        name, separator, value = (part.strip() for part in item.partition("="))
        if not separator or not value:
            raise ValueError(f"Budget set entries must be name=value, not {item.strip()!r}")
        if name in TASK_FLAG_FIELDS:
            if value.lower() not in {"true", "false"}:
                raise ValueError(f"{name} must be true or false, not {value!r}")
            budgets[name] = value.lower() == "true"
        elif value == UNLIMITED_BUDGET:
            budgets[name] = value
        else:
            try:
                budgets[name] = int(value)
            except ValueError as exc:
                raise ValueError(f"Budget {name} must be an integer, not {value!r}") from exc
    return _validated_budget_set(budgets)


def _validated_budget_set(budgets: Mapping[str, Any]) -> dict[str, int | bool | str]:
    unknown = sorted(set(budgets) - set(TASK_OVERRIDE_FIELDS))
    if unknown:
        raise ValueError(f"Unknown task budget(s): {', '.join(unknown)}")
    return task_budget_overrides(dict(budgets))


def _budget_set_label(budgets: Mapping[str, int | bool]) -> str:
    return ",".join(
        f"{name}={str(value).lower() if isinstance(value, bool) else value}"
        for name, value in sorted(budgets.items())
    ) or "none"


def read_smiles_file(path: str | Path) -> list[str]:
    """Read one-SMILES-per-line files with an optional `SMILES` header."""

    smiles: list[str] = []
    source = Path(path)
    with source.open("r", encoding="utf-8") as handle:
        for line_number, raw_line in enumerate(handle, start=1):
            value = raw_line.strip()
            if not value:
                continue
            if line_number == 1 and value.lower() == "smiles":
                continue
            smiles.append(value)
    return smiles


def generate_llm_taskset(
    source_path: str | Path,
    output_path: str | Path,
    dataset: str,
    limit: int | None = None,
    tool_exclusion_sets: Sequence[Sequence[str]] = ((),),
    tool_exclusion_seed: int = 0,
    budget_sets: Sequence[Mapping[str, int | bool]] = ({},),
    budget_seed: int = 0,
) -> dict[str, Any]:
    """Convert a SynFormer-style SMILES test set into JSONL LLM tasks.

    Each task excludes one of ``tool_exclusion_sets``, drawn uniformly with ``tool_exclusion_seed``,
    and takes one of ``budget_sets``, drawn uniformly with ``budget_seed``. The draws are
    independent, so adding budget sets leaves each task's tool exclusions unchanged.
    """

    source = Path(source_path)
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)

    stats: dict[str, Any] = {
        "source_file": str(source),
        "output_file": str(output),
        "dataset": dataset,
        "read": 0,
        "written": 0,
        "invalid": 0,
        "chem_backend": chem.backend_name(),
    }

    records = read_smiles_file(source)
    if limit is not None:
        records = records[: max(0, int(limit))]
    exclusion_sets = [sorted(normalize_excluded_tools(item)) for item in tool_exclusion_sets]
    if not exclusion_sets:
        raise ValueError("tool_exclusion_sets must contain at least one set")
    rng = random.Random(tool_exclusion_seed)
    stats["tool_exclusion_counts"] = {",".join(item) or "none": 0 for item in exclusion_sets}
    # Validated here, so a bad budget set fails the command rather than counting rows as invalid.
    validated_budget_sets = [_validated_budget_set(item) for item in budget_sets]
    if not validated_budget_sets:
        raise ValueError("budget_sets must contain at least one set")
    budget_rng = random.Random(budget_seed)
    stats["budget_set_counts"] = {_budget_set_label(item): 0 for item in validated_budget_sets}

    with output.open("w", encoding="utf-8") as handle:
        for index, smiles in enumerate(records, start=1):
            stats["read"] += 1
            task_id = f"{dataset}-{index:04d}"
            # Drawn for every row, so a row's set doesn't depend on which rows are invalid.
            excluded = rng.choice(exclusion_sets)
            budgets = budget_rng.choice(validated_budget_sets)
            try:
                task = build_llm_task(
                    smiles,
                    task_id=task_id,
                    dataset=dataset,
                    source_file=str(source),
                    excluded_tools=excluded,
                    budgets=budgets,
                )
            except ValueError:
                stats["invalid"] += 1
                continue
            handle.write(json.dumps(task, sort_keys=True) + "\n")
            stats["written"] += 1
            stats["tool_exclusion_counts"][",".join(excluded) or "none"] += 1
            stats["budget_set_counts"][_budget_set_label(budgets)] += 1
    return stats
